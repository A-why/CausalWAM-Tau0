#!/usr/bin/env python3
"""V3-B0 Phase C (RoboTwin side): K=8 SDE candidate sign probe on native snapshots.

For each simulator-native snapshot S0-S3, restores the full simulator state into a fresh
env and executes each of K=8 SDE candidate action chunks (generated by the Tau side). The
outcome is Y = max switch qpos over the H=33 horizon. Paired against the hold reference
Y0 (already measured), G_true = Y - Y0 is classified positive/neutral/negative.

No VAM. No ACVS. No training. optimizer.step = 0.

Usage:
    cd ${ROBOTWIN_ROOT} && DISPLAY=:99 PYTHONUNBUFFERED=1 CUDA_VISIBLE_DEVICES=0 \
    /opt/conda/envs/robotwin/bin/python ${CAUSALWAM_ROOT}/eval/v3b0_sign_probe.py
"""
import sys, os, json, pickle, random, argparse, yaml
import numpy as np

ROBOTWIN_ROOT = os.environ.get("ROBOTWIN_ROOT", "/data/QWW/RoboTwin")
CAUSAL_ROOT = os.environ.get("CAUSALWAM_ROOT", os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROBOTWIN_ROOT)
sys.path.insert(0, os.path.join(ROBOTWIN_ROOT, "description/utils"))

TASK = "turn_switch"
OUT_ROOT = os.path.join(CAUSAL_ROOT, "outputs/v3b0_outcome_contract")
SNAP_DIR = os.path.join(OUT_ROOT, "native_snapshots")
CAND_JSONL = os.path.join(OUT_ROOT, "sde_candidates", "candidates.jsonl")
SEED = 0
HORIZON = 33
NEUTRAL_EPS = 5e-3  # G_true band considered "neutral" (5e-3 rad ~ 2.6% of travel)
MAX_RETRIES = 2
SNAPSHOTS = ["S0", "S1", "S2", "S3"]


def init_task_env(seed):
    from envs.turn_switch import turn_switch
    from envs import CONFIGS_PATH
    task_env = turn_switch()
    with open(os.path.join(ROBOTWIN_ROOT, "task_config/demo_clean.yml")) as f:
        args = yaml.load(f.read(), Loader=yaml.FullLoader)
    with open(os.path.join(CONFIGS_PATH, "_embodiment_config.yml")) as f:
        emb_types = yaml.load(f.read(), Loader=yaml.FullLoader)
    embodiment_type = args.get("embodiment", ["aloha-agilex"])
    robot_file = emb_types[embodiment_type[0]]["file_path"]

    def get_emb(rf):
        with open(os.path.join(rf, "config.yml")) as f:
            return yaml.load(f.read(), Loader=yaml.FullLoader)

    args["task_name"] = TASK
    args["left_robot_file"] = robot_file
    args["right_robot_file"] = robot_file
    args["dual_arm_embodied"] = True
    args["left_embodiment_config"] = get_emb(robot_file)
    args["right_embodiment_config"] = get_emb(robot_file)
    head_cam = args["camera"]["head_camera_type"]
    with open(os.path.join(CONFIGS_PATH, "_camera_config.yml")) as f:
        cam_cfg = yaml.load(f.read(), Loader=yaml.FullLoader)
    args["head_camera_h"] = cam_cfg[head_cam]["h"]
    args["head_camera_w"] = cam_cfg[head_cam]["w"]
    args["seed"] = seed
    args["save_data"] = False
    args["eval_mode"] = False
    args["data_type"] = {"rgb": True, "endpose": True, "qpos": False, "depth": False}
    args["render_freq"] = 0
    args["need_plan"] = True
    args["collect_data"] = False
    task_env.setup_demo(**args)
    return task_env


def get_switch_qpos(task_env):
    try:
        if hasattr(task_env, 'switch'):
            qpos = task_env.switch.get_qpos()
            if qpos is not None and len(qpos) > 0:
                return float(qpos[0])
    except Exception:
        pass
    return None


def restore_snapshot(task_env, full_state):
    fs = full_state
    sw = task_env.switch
    sw.set_qpos(np.asarray(fs["switch"]["qpos"], dtype=np.float64))
    qvel = fs["switch"].get("qvel")
    sw.set_qvel(np.asarray(qvel, dtype=np.float64) if qvel is not None
                else np.zeros_like(np.asarray(fs["switch"]["qpos"])))

    rob = task_env.robot._entity
    rob.set_qpos(np.asarray(fs["robot"]["qpos"], dtype=np.float64))
    rqvel = fs["robot"].get("qvel")
    rob.set_qvel(np.asarray(rqvel, dtype=np.float64) if rqvel is not None
                 else np.zeros_like(np.asarray(fs["robot"]["qpos"])))

    rng = fs.get("rng", {})
    if rng.get("numpy") is not None:
        try:
            np.random.set_state(rng["numpy"])
        except Exception:
            pass
    if rng.get("random") is not None:
        try:
            random.setstate(rng["random"])
        except Exception:
            pass


def run_rollout(task_env, action_chunk_16):
    trace = []
    for t in range(HORIZON):
        try:
            task_env.take_action(action_chunk_16[t], action_type='ee')
        except Exception as e:
            return None, f"take_action step {t}: {e}"
        q = get_switch_qpos(task_env)
        trace.append(q if q is not None else None)
    ys = [q for q in trace if q is not None]
    Y = float(max(ys)) if ys else 0.0
    return Y, trace, None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--snapshots", nargs="+", default=SNAPSHOTS)
    args = parser.parse_args()

    # threshold from manifest
    with open(os.path.join(SNAP_DIR, "manifest.json")) as f:
        manifest = json.load(f)
    SUCCESS_THRESHOLD = float(manifest["threshold"])

    # hold reference
    with open(os.path.join(OUT_ROOT, "hold_reference.json")) as f:
        hold = json.load(f)["hold_reference"]

    candidates = []
    with open(CAND_JSONL) as f:
        for line in f:
            line = line.strip()
            if line:
                candidates.append(json.loads(line))
    print(f"Loaded {len(candidates)} candidates, threshold={SUCCESS_THRESHOLD:.6f}", flush=True)

    records = []

    for snap in args.snapshots:
        with open(os.path.join(SNAP_DIR, f"{snap}.pkl"), "rb") as f:
            snap_data = pickle.load(f)
        fs = snap_data["full_state"]
        saved_qpos = snap_data["switch_qpos"]
        Y0 = float(hold[snap]["Y0"])
        snap_cands = [c for c in candidates if c["snapshot_id"] == snap]
        print(f"\n{'='*60}\nSnapshot {snap} (saved_qpos={saved_qpos:.6f}, Y0={Y0:.6f})\n{'='*60}", flush=True)

        for cand in snap_cands:
            cid = cand["candidate_id"]
            rtw_chunk = np.asarray(cand["robotwin_absolute_action"], dtype=np.float32)  # (33,16)
            rec = None
            for attempt in range(MAX_RETRIES + 1):
                task_env = init_task_env(SEED)
                try:
                    restore_snapshot(task_env, fs)
                    pre_qpos = get_switch_qpos(task_env)
                    if abs(pre_qpos - saved_qpos) > 1e-6:
                        raise RuntimeError(f"restore readback {pre_qpos:.6f} != saved {saved_qpos:.6f}")
                    Y, trace, err = run_rollout(task_env, rtw_chunk)
                    if err is not None:
                        raise RuntimeError(err)
                    G = float(Y - Y0)
                    if G > NEUTRAL_EPS:
                        sign = "positive"
                    elif G < -NEUTRAL_EPS:
                        sign = "negative"
                    else:
                        sign = "neutral"
                    rec = {
                        "candidate_id": cid,
                        "snapshot_id": snap,
                        "sde_rng_seed": cand["sde_rng_seed"],
                        "trajectory_hash": cand["trajectory_hash"],
                        "saved_qpos": saved_qpos,
                        "pre_qpos": pre_qpos,
                        "Y0": Y0,
                        "Y": Y,
                        "G_true": G,
                        "sign": sign,
                        "success": bool(Y >= SUCCESS_THRESHOLD),
                        "attempts": attempt + 1,
                        "error": None,
                    }
                    task_env.close()
                    break
                except Exception as e:
                    task_env.close()
                    print(f"  {cid} attempt {attempt+1} fault: {e}", flush=True)
                    rec = {"candidate_id": cid, "snapshot_id": snap,
                           "sde_rng_seed": cand["sde_rng_seed"], "error": str(e),
                           "Y": None, "G_true": None, "sign": None}
            records.append(rec)
            if rec.get("error") is None:
                print(f"  {cid}: pre={rec['pre_qpos']:.6f} Y={rec['Y']:.6f} "
                      f"G_true={rec['G_true']:+.6f} sign={rec['sign']} success={rec['success']}", flush=True)
            else:
                print(f"  {cid}: ERROR {rec['error'][:80]}", flush=True)

    out_jsonl = os.path.join(OUT_ROOT, "sign_probe_results.jsonl")
    with open(out_jsonl, "w") as f:
        f.write(json.dumps({"type": "header", "horizon": HORIZON,
                            "neutral_eps": NEUTRAL_EPS,
                            "success_threshold": SUCCESS_THRESHOLD,
                            "hold_reference": hold}) + "\n")
        for r in records:
            f.write(json.dumps(r) + "\n")
    print(f"\nSaved {len(records)} sign-probe records -> {out_jsonl}", flush=True)

    # summary
    from collections import defaultdict
    by_snap = defaultdict(lambda: {"positive": 0, "negative": 0, "neutral": 0, "error": 0,
                                   "success": 0, "G_true": []})
    for r in records:
        s = r["snapshot_id"]
        if r.get("error"):
            by_snap[s]["error"] += 1
        else:
            by_snap[s][r["sign"]] += 1
            if r["success"]:
                by_snap[s]["success"] += 1
            by_snap[s]["G_true"].append(r["G_true"])
    print("\nSign-probe summary:", flush=True)
    for s in SNAPSHOTS:
        d = by_snap[s]
        g = d["G_true"]
        print(f"  {s}: positive={d['positive']} neutral={d['neutral']} negative={d['negative']} "
              f"error={d['error']} success={d['success']} "
              f"G_true[min,max]=[{min(g) if g else 'n/a'}, {max(g) if g else 'n/a'}]", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
